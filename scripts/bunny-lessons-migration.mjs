/**
 * Writes the Prisma migration that gives each migrated class its video lesson
 * (DEC-090). Reads the Drive → Bunny ledger and turns every video that passed
 * verification (encoded, length matches Drive, signed playback worked) and is
 * not in an earlier migration into SQL, so the change reaches production the
 * way every schema change does: `prisma migrate deploy` on the next deploy.
 *
 *   node scripts/bunny-lessons-migration.mjs --name=class_video_lessons_batch1 --dry-run
 *   node scripts/bunny-lessons-migration.mjs --name=class_video_lessons_batch1
 *
 * For each video the SQL, inside one DO block:
 *   - skips it if a lesson already carries that Bunny video (re-runs are no-ops);
 *   - skips the class if its course is not in the database (logged as a NOTICE);
 *   - otherwise, if the course already has a video lesson with no Bunny video
 *     (one made by hand in the console), sets only that lesson's bunnyVideoId;
 *   - otherwise adds a "Class recording" section (once) and a published VIDEO
 *     lesson in it carrying the video, its length and Bunny's ready status.
 * Course rows (titles, photos, descriptions, categories, resources) are never
 * touched. Course slugs come from docs/migration/class-course-slugs.json, read
 * from production.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";

const LEDGER = "docs/migration/bunny-ledger.json";
const SLUGS = "docs/migration/class-course-slugs.json";
const args = process.argv.slice(2);
const name = args.find((arg) => arg.startsWith("--name="))?.split("=")[1];
const dryRun = args.includes("--dry-run");
if (!name || !/^[a-z0-9_]+$/.test(name)) throw new Error("Pass --name=<lowercase_with_underscores>");

const ledger = JSON.parse(readFileSync(LEDGER, "utf8"));
const slugs = JSON.parse(readFileSync(SLUGS, "utf8"));

const slugify = (text) => text.toLowerCase().replace(/&/g, " and ").replace(/['’]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
const sql = (value) => (value === null || value === undefined ? "NULL" : typeof value === "number" ? String(value) : `'${String(value).replace(/'/g, "''")}'`);

const ready = Object.values(ledger).filter((entry) => !entry.lessonMigration && entry.bunnyStatus === 4 && entry.verified?.ok && entry.playback?.ok);
const skipped = Object.values(ledger).filter((entry) => !entry.lessonMigration && !ready.includes(entry));
const rows = [];
const noCourse = [];
for (const entry of ready.sort((a, b) => a.classNumber - b.classNumber || String(a.part).localeCompare(String(b.part)))) {
  const courseSlug = slugs[entry.class];
  if (!courseSlug) {
    noCourse.push(entry);
    continue;
  }
  const [part, parts] = entry.part ? entry.part.split(" of ").map(Number) : [1, 1];
  // One recording: "The full class". Several (a pack or bundle): each under its own name.
  const lessonTitle = parts > 1 ? entry.driveName.replace(/\.[a-z0-9]+$/i, "").trim() : "The full class";
  rows.push({
    entry,
    courseSlug,
    sectionTitle: parts > 1 ? "Class recordings" : "Class recording",
    lessonSlug: slugify(lessonTitle),
    lessonTitle,
    sortOrder: part - 1,
    videoId: entry.bunnyVideoId.toLowerCase(),
    lengthSeconds: entry.lengthSeconds,
    durationMin: Math.max(1, Math.round(entry.lengthSeconds / 60)),
  });
}

if (rows.length === 0) {
  console.log("No verified videos waiting for a lesson.");
  if (noCourse.length) console.log("Verified but no course:", noCourse.map((e) => e.class));
  process.exit(0);
}

const values = rows
  .map((row, index) =>
    `    (${[row.courseSlug, row.sectionTitle, row.lessonSlug, row.lessonTitle, row.sortOrder, row.videoId, row.lengthSeconds, row.durationMin].map(sql).join(", ")})` +
    `${index < rows.length - 1 ? "," : ""} -- #${row.entry.classNumber} ${row.entry.class}`,
  )
  .join("\n");

const body = `-- Class video lessons (DEC-090): ${rows.length} Bunny video(s) from the Drive migration.
-- Generated by scripts/bunny-lessons-migration.mjs from docs/migration/bunny-ledger.json.
-- Adds a section and a published VIDEO lesson per video to its class, or, where
-- the class already has a video lesson with no Bunny video, sets only that
-- lesson's bunnyVideoId. Course rows are not touched. Safe to re-run.
DO $$
DECLARE
  r record;
  v_course text;
  v_section text;
  v_existing text;
BEGIN
  FOR r IN SELECT * FROM (VALUES
${values}
  ) AS v(course_slug, section_title, lesson_slug, lesson_title, sort_order, video_id, length_s, duration_min)
  LOOP
    IF EXISTS (SELECT 1 FROM "Lesson" WHERE "bunnyVideoId" = r.video_id) THEN
      CONTINUE;
    END IF;

    SELECT id INTO v_course FROM "Course" WHERE slug = r.course_slug;
    IF v_course IS NULL THEN
      RAISE NOTICE 'class video %: no course "%", skipped', r.video_id, r.course_slug;
      CONTINUE;
    END IF;

    SELECT l.id INTO v_existing
      FROM "Lesson" l JOIN "CourseSection" s ON s.id = l."sectionId"
      WHERE s."courseId" = v_course AND l.kind = 'VIDEO' AND l."bunnyVideoId" IS NULL
      ORDER BY s."sortOrder", l."sortOrder"
      LIMIT 1;
    IF v_existing IS NOT NULL THEN
      UPDATE "Lesson" SET "bunnyVideoId" = r.video_id WHERE id = v_existing;
      RAISE NOTICE 'class video %: attached to existing lesson % in "%"', r.video_id, v_existing, r.course_slug;
      CONTINUE;
    END IF;

    SELECT id INTO v_section FROM "CourseSection"
      WHERE "courseId" = v_course AND title = r.section_title
      ORDER BY "sortOrder" LIMIT 1;
    IF v_section IS NULL THEN
      v_section := 'sec_' || md5(r.course_slug || '/' || r.section_title);
      INSERT INTO "CourseSection" (id, "courseId", title, "sortOrder")
      VALUES (v_section, v_course, r.section_title, 0);
    END IF;

    INSERT INTO "Lesson" (
      id, "sectionId", title, slug, kind, "durationMin",
      "bunnyVideoId", "bunnyVideoStatus", "bunnyVideoLength", "bunnySyncedAt",
      "isPreview", published, "sortOrder", "updatedAt"
    )
    VALUES (
      'les_' || md5(r.video_id), v_section, r.lesson_title, r.lesson_slug, 'VIDEO', r.duration_min,
      r.video_id, 4, r.length_s, now(),
      false, true, r.sort_order, now()
    )
    ON CONFLICT ("sectionId", slug) DO NOTHING;
  END LOOP;
END $$;
`;

console.log(`${rows.length} lesson(s):`);
for (const row of rows) console.log(`  #${row.entry.classNumber} ${row.courseSlug} › ${row.sectionTitle} › ${row.lessonTitle} (${row.durationMin} min) ← ${row.videoId}`);
if (noCourse.length) console.log(`Verified but no course in production (not in this migration): ${noCourse.map((e) => e.class).join("; ")}`);
if (skipped.length) console.log(`Not yet verified (left for a later migration): ${skipped.length}`);
if (dryRun) {
  console.log("\n" + body);
  process.exit(0);
}

const stamp = new Date().toISOString().replace(/\D/g, "").slice(0, 14);
const dir = `prisma/migrations/${stamp}_${name}`;
if (existsSync(dir)) throw new Error(`${dir} exists`);
mkdirSync(dir, { recursive: true });
writeFileSync(`${dir}/migration.sql`, body);
for (const row of rows) Object.assign(row.entry, { lessonMigration: `${stamp}_${name}`, courseSlug: row.courseSlug, lessonSlug: row.lessonSlug });
writeFileSync(LEDGER, JSON.stringify(ledger, null, 2) + "\n");
console.log(`Wrote ${dir}/migration.sql and marked ${rows.length} ledger row(s).`);
